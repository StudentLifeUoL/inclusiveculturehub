  function icon(name, opts) {
    opts = opts || {};
    var body = ICONS[name] || "";
    var size = opts.size || 24;
    var cls = opts.cls ? ' class="' + opts.cls + '"' : "";
    var a11y = opts.label
      ? ' role="img" aria-label="' + esc(opts.label) + '"'
      : ' aria-hidden="true" focusable="false"';
    return '<svg' + cls + a11y + ' xmlns="http://www.w3.org/2000/svg" width="' + size + '" height="' + size +
      '" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="' + (opts.stroke || 2) +
      '" stroke-linecap="round" stroke-linejoin="round">' + body + "</svg>";
  }

  // Replace <i data-icon="name"></i> placeholders with inline SVG.
  function hydrateIcons(root) {
    (root || document).querySelectorAll("i[data-icon]").forEach(function (el) {
      var tmp = document.createElement("span");
      tmp.innerHTML = icon(el.getAttribute("data-icon"), { cls: el.className || "" });
      el.replaceWith(tmp.firstChild);
    });
  }

  function esc(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
      .replace(/"/g, "&quot;").replace(/'/g, "&#39;");
  }

  function wordCount(text) {
    var m = String(text || "").trim().match(/[\p{L}\p{N}][\p{L}\p{N}'’-]*/gu);
    return m ? m.length : 0;
  }

  // ---------- Storage ----------
  function makeStore(ns) {
    var prefix = "ich:" + ns + ":";
    return {
      get: function (key, fallback) {
        try {
          var raw = window.localStorage.getItem(prefix + key);
          return raw == null ? fallback : JSON.parse(raw);
        } catch (e) { return fallback; }
      },
      set: function (key, value) {
        try { window.localStorage.setItem(prefix + key, JSON.stringify(value)); return true; }
        catch (e) { return false; }
      },
      remove: function (key) {
        try { window.localStorage.removeItem(prefix + key); } catch (e) {}
      }
    };
  }

  // ---------- Getting work out ----------
  function download(filename, text) {
    try {
      var blob = new Blob(["﻿" + text], { type: "text/plain;charset=utf-8" });
      var url = URL.createObjectURL(blob);
      var a = document.createElement("a");
      a.href = url;
      a.download = filename;
      a.rel = "noopener";
      document.body.appendChild(a);
      a.click();
      a.remove();
      setTimeout(function () { URL.revokeObjectURL(url); }, 4000);
      return true;
    } catch (e) { return false; }
  }

  function copy(text) {
    function fallback() {
      try {
        var ta = document.createElement("textarea");
        ta.value = text;
        ta.setAttribute("readonly", "");
        ta.style.position = "fixed";
        ta.style.top = "-1000px";
        document.body.appendChild(ta);
        ta.select();
        var ok = document.execCommand("copy");
        ta.remove();
        return ok;
      } catch (e) { return false; }
    }
    if (navigator.clipboard && window.isSecureContext) {
      return navigator.clipboard.writeText(text).then(function () { return true; }, function () { return fallback(); });
    }
    return Promise.resolve(fallback());
  }

  function dateStamp() {
    var d = new Date();
    return d.toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" });
  }

  // ---------- Live announcements for screen readers ----------
  var live;
  function announce(msg) {
    if (!live) {
      live = document.createElement("div");
      live.className = "sr-only";
      live.setAttribute("aria-live", "polite");
      document.body.appendChild(live);
    }
    live.textContent = "";
    setTimeout(function () { live.textContent = msg; }, 60);
  }

  // Rise 360 code blocks mark completion when they receive this message.
  var completed = false;
  function complete() {
    if (completed) return;
    completed = true;
    try { window.parent.postMessage({ type: "complete" }, "*"); } catch (e) {}
  }

  // ---------- Word meter ----------
  function meter(el, words, min, max) {
    if (!el) return;
    var scale = max * 1.25;
    var fill = el.querySelector(".meter-fill");
    var zone = el.querySelector(".meter-zone");
    var text = el.querySelector(".meter-text");
    if (zone) { zone.style.left = (min / scale * 100) + "%"; zone.style.width = ((max - min) / scale * 100) + "%"; }
    if (fill) fill.style.width = Math.min(100, words / scale * 100) + "%";
    el.dataset.state = words === 0 ? "empty" : words < min ? "under" : words <= max ? "in" : "over";
    if (text) {
      var unit = words === 1 ? " word" : " words";
      text.textContent = words + unit + (words > max ? " · a little over" : words >= min ? " · good length" : " · aim for " + min + " to " + max);
    }
  }

