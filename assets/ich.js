  // ---------- Flow: one step visible at a time ----------
  function flow(cfg) {
    cfg = cfg || {};
    var app = document.querySelector(cfg.root || ".app");
    var steps = Array.prototype.slice.call(app.querySelectorAll(".step"));
    var names = steps.map(function (s) { return s.getAttribute("data-step"); });
    var back = app.querySelector('[data-nav="back"]');
    var next = app.querySelector('[data-nav="next"]');
    var count = app.querySelector("[data-count]");
    var nudge = app.querySelector("[data-nudge]");
    var progress = app.querySelector(".progress ol");
    var crowd = app.querySelector("[data-crowd]");
    var current = -1;
    var hooks = cfg.steps || {};

    if (crowd) {
      crowd.setAttribute("viewBox", "0 0 156 46");
      crowd.innerHTML = crowdSVG();
    }
    if (progress) {
      progress.innerHTML = steps.map(function (s, i) {
        return '<li data-state="todo"><span class="bar"></span><span class="lbl">' + esc(s.getAttribute("data-label") || "Step " + (i + 1)) + "</span></li>";
      }).join("");
    }

    function hook(name, key) { return hooks[name] && hooks[name][key]; }

    function check() {
      var name = names[current];
      var fn = hook(name, "ready");
      var res = fn ? fn() : true;
      return res === true || res === undefined ? true : res;
    }

    function refresh() {
      var name = names[current];
      var ok = check();
      next.setAttribute("aria-disabled", ok === true ? "false" : "true");
      // Keep a visible nudge in step with the current state (e.g. "Choose 2 more" becomes "Choose 1 more").
      if (nudge && nudge.textContent) nudge.textContent = ok === true ? "" : (typeof ok === "string" ? ok : "Complete this step to continue.");
      var label = hook(name, "next") || (current === steps.length - 1 ? "Start again" : "Continue");
      var ic = current === steps.length - 1 ? icon("rotate-ccw") : icon("arrow-right");
      var showNext = hook(name, "hideNext") ? false : true;
      next.hidden = !showNext;
      next.innerHTML = '<span>' + esc(label) + "</span>" + ic;
    }

    function go(i, opts) {
      opts = opts || {};
      if (i < 0 || i >= steps.length) return;
      var prev = current;
      if (prev >= 0) {
        var leave = hook(names[prev], "leave");
        if (leave) leave();
      }
      current = i;
      steps.forEach(function (s, k) { s.hidden = k !== i; });
      if (progress) {
        progress.querySelectorAll("li").forEach(function (li, k) {
          li.setAttribute("data-state", k < i ? "done" : k === i ? "current" : "todo");
          if (k === i) li.setAttribute("aria-current", "step"); else li.removeAttribute("aria-current");
        });
      }
      if (crowd) paintCrowd(crowd, Math.round((i + 1) / steps.length * 7));
      if (count) count.textContent = "Step " + (i + 1) + " of " + steps.length;
      if (back) back.style.visibility = i === 0 ? "hidden" : "visible";
      var enter = hook(names[i], "enter");
      if (enter) enter();
      refresh();
      if (nudge) nudge.textContent = "";
      if (!opts.initial) {
        try { window.scrollTo({ top: 0, behavior: "auto" }); } catch (e) { window.scrollTo(0, 0); }
        var h = steps[i].querySelector(".step-title");
        if (h) { h.setAttribute("tabindex", "-1"); try { h.focus({ preventScroll: true }); } catch (e) { h.focus(); } }
      }
      if (i === steps.length - 1 && cfg.completeOnLast !== false) complete();
      if (cfg.onChange) cfg.onChange(names[i], i);
    }

    if (next) next.addEventListener("click", function () {
      var ok = check();
      if (ok !== true) {
        if (nudge) nudge.textContent = typeof ok === "string" ? ok : "Complete this step to continue.";
        return;
      }
      var custom = hook(names[current], "onNext");
      if (custom) { custom(); return; }
      if (current === steps.length - 1) { if (cfg.onRestart) cfg.onRestart(); go(0); }
      else go(current + 1);
    });
    if (back) back.addEventListener("click", function () { go(current - 1); });

    hydrateIcons(app);
    go(cfg.start || 0, { initial: true });

    return {
      go: function (nameOrIndex) { go(typeof nameOrIndex === "number" ? nameOrIndex : names.indexOf(nameOrIndex)); },
      next: function () { go(current + 1); },
      refresh: refresh,
      current: function () { return names[current]; }
    };
  }

